/* =========================================================
   FORMAT BOT MESSAGE
   ========================================================= */

function formatMessage(message) {

    let safe =
        escapeHTML(message);


    safe =
        safe.replace(
            /\*\*(.*?)\*\*/g,
            "<strong>$1</strong>"
        );


    safe =
        safe.replace(
            /\n/g,
            "<br>"
        );


    return safe;

}



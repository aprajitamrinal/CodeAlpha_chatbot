const chatBox = document.getElementById("chat-box");
const userInput = document.getElementById("user-input");


/* =========================================================
   NORMALIZE QUESTION
   ========================================================= */

function normalizeQuestion(text) {

    return text
        .toLowerCase()
        .trim()
        .replace(/[?!.,]/g, "")
        .replace(/\s+/g, " ");

}


/* =========================================================
   SEND MESSAGE
   ========================================================= */

function sendMessage() {

    const message = userInput.value.trim();

    if (!message) {
        return;
    }

    addUserMessage(message);

    userInput.value = "";

    userInput.focus();

    showTyping();

    const csrfToken = getCSRFToken();

    fetch("/chat/", {

        method: "POST",

        headers: {
            "Content-Type":
                "application/x-www-form-urlencoded",
            "X-CSRFToken": csrfToken
        },

        body:
            "message=" +
            encodeURIComponent(message)

    })

    .then(response => {

        if (!response.ok) {
            throw new Error(
                "Server Error: " +
                response.status
            );
        }

        return response.json();

    })

    .then(data => {

        removeTyping();

        setTimeout(() => {

            addBotMessage(
                data.response,
                message
            );

        }, 350);

    })

    .catch(error => {

        console.error(
            "Chatbot Error:",
            error
        );

        removeTyping();

        addBotMessage(
            "Sorry 😕 I couldn't process that message right now. Please try again.",
            ""
        );

    });

}


/* =========================================================
   ENTER KEY
   ========================================================= */

if (userInput) {

    userInput.addEventListener(
        "keydown",
        function (event) {

            if (
                event.key === "Enter" &&
                !event.shiftKey
            ) {

                event.preventDefault();

                sendMessage();

            }

        }
    );

}


